#to create houses
def house(color1,color2):
       t.pencolor("black")
       t.begin_fill()
       t.fillcolor(color1)
       for x in range(4):
              t.fd(100)
              t.left(90)
       t.end_fill()
       t.up()
       t.fd(100)
       t.down()
       t.pencolor("black")
       t.begin_fill()
       t.fillcolor(color2)
       t.left(45)
       t.forward(75)
       t.left(90)
       t.fd(75)
       t.end_fill()
       
