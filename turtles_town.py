# to create flowers
def flower(color1,color2,color3):
       t.color(color1)
       t.setheading(90)
       t.fd(30)
       t.right(45)
       t.fd(25)
       t.up()
       t.backward(25)
       t.left(45)
       t.down()
       t.fd(40)
       t.color(color2)
