import turtle 
t=turtle.Turtle()
t.speed(1)
w=turtle.Screen()
w.bgcolor("black")
t.begin_fill()
t.fillcolor("yellow")
t.circle(100)
t.end_fill()
t.up()
t.setpos(-50,100)
t.down()
t.begin_fill()
t.fillcolor("blue")
t.circle(20)
t.end_fill()
t.up()
t.setpos(50,100)
t.down()
t.begin_fill()
t.fillcolor("blue")
t.circle(20)
t.end_fill()
t.up()
t.setpos(-45,60)
t.down()
t.pencolor("black")
t.width(10)
t.right(45)
for i in range(90):
    t.fd(1)
    t.left(1)
turtle.mainloop()

