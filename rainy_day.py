def cloud(color):
       t.begin_fill()
       t.fillcolor(color)
       t.circle(45)
       t.right(100)
       t.circle(50)
       t.left(180)
       t.circle(50)
       t.left(45)
       t.circle(50)
       t.up()
       t.setheading(180)
       t.fd(50)
       t.down()
       for x in range(11):
             t.left(45)
             t.circle(50)
       t.end_fill()
def rain(x,y):
    t.pensize(3)
    t.up()
    t.goto(x,y)
    t.setheading(270)
    t.down()
    t.color("blue")
    t.fd(7)

def flower(color1,color2,color3):
       t.color(color1)
       t.setheading(90)
       t.fd(30)
       t.right(45)
       t.fd(25)
       t.up()
       t.backward(25)
       t.left(45)
       t.down()
       t.fd(40)
       t.color(color2)
       t.begin_fill()
       t.fillcolor(color3)
       t.circle(20)
       t.end_fill()
